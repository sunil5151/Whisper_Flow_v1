'use strict';

// .memory/TASKS.md — generated from records/tasks.jsonl (P3).

const path = require('node:path');
const { memoryDir } = require('../paths');
const state = require('./state');

const ACTIVE = ['open', 'in_progress', 'blocked', 'implemented_unverified'];
const COMPLETED = ['done', 'verified'];
const COMPLETED_MAX = 30;

function cell(text) {
  return state.oneLine(text, 120).replace(/\|/g, '\\|');
}

function row(t) {
  return '| `' + t.id + '` | ' + [
    cell(state.label(t)), t.status + (t.downgraded ? ' (downgraded)' : ''), t.priority || 'unranked',
    t.effort_estimate || '?', t.capability || '?', cell((t.blockers || []).join('; '))
  ].join(' | ') + ' |';
}

function renderTasks(root, { now = new Date(), loaded = state.loadState(root) } = {}) {
  const tasks = loaded.all.filter((r) => r.type === 'task');
  const active = tasks.filter((t) => ACTIVE.includes(t.status)).sort(state.byPriorityAge);
  const done = tasks.filter((t) => COMPLETED.includes(t.status)).sort(state.byTsDesc).slice(0, COMPLETED_MAX);
  const lines = [
    '# Tasks — ' + path.basename(path.resolve(root)),
    'Generated: ' + state.display(now),
    '> Generated by MEMO from .memory/records/tasks.jsonl. Do not edit.',
    '',
    '## Open, in progress, blocked',
    ''
  ];
  if (active.length === 0) lines.push('(none)');
  else lines.push('| ID | Title | Status | Priority | Effort | Capability | Blockers |',
    '|---|---|---|---|---|---|---|', ...active.map(row));
  lines.push('', `## Completed (last ${COMPLETED_MAX})`, '');
  if (done.length === 0) lines.push('(none)');
  else lines.push('| ID | Title | Status | Completed | Evidence |', '|---|---|---|---|---|',
    ...done.map((t) => '| `' + t.id + '` | ' + cell(state.label(t)) + ' | ' + t.status + ' | ' +
      String(t.ts || '').slice(0, 10) + ' | ' + cell((t.completion_evidence || t.evidence || []).slice(0, 3).join(', ')) + ' |'));
  return lines.join('\n') + '\n';
}

function tasksPath(root) {
  return path.join(memoryDir(root), 'TASKS.md');
}

function writeTasks(root, opts = {}) {
  return state.writeKeepingHeader(tasksPath(root), renderTasks(root, opts));
}

module.exports = { renderTasks, writeTasks, tasksPath };
